CREATE TABLE IF NOT EXISTS BOARD (
    IDX INT NOT NULL AUTO_INCREMENT,
    U_CODE INT NOT NULL,
    B_NICK VARCHAR(50) NOT NULL,
    B_TITLE VARCHAR(200) NOT NULL,
    B_CONTENTS TEXT NOT NULL,
    B_CNT INT NOT NULL DEFAULT 0,
    DEL_CHK CHAR(1) NOT NULL DEFAULT 'N',
    REG_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (IDX),
    CONSTRAINT FK_BOARD_USER FOREIGN KEY (U_CODE) REFERENCES USER (U_CODE)
);

CREATE TABLE IF NOT EXISTS GAMELIST (
    G_CODE INT NOT NULL AUTO_INCREMENT,
    G_DUNG INT NOT NULL,
    G_SEARCH INT,
    G_DATE DATE NOT NULL,
    G_TIME TIME NOT NULL,
    G_PEO VARCHAR(30) NOT NULL,
    G_MAGAM INT NOT NULL DEFAULT 1,
    F_CODE INT NOT NULL,
    G_INTRO VARCHAR(500),
    REG_DATE DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (G_CODE),
    CONSTRAINT FK_GAMELIST_HOME_TEAM FOREIGN KEY (G_DUNG) REFERENCES TEAM (T_CODE),
    CONSTRAINT FK_GAMELIST_AWAY_TEAM FOREIGN KEY (G_SEARCH) REFERENCES TEAM (T_CODE),
    CONSTRAINT FK_GAMELIST_FIELD FOREIGN KEY (F_CODE) REFERENCES FINFO (F_CODE)
);

CREATE TABLE IF NOT EXISTS persistent_logins (
    username VARCHAR(64) NOT NULL,
    series VARCHAR(64) PRIMARY KEY,
    token VARCHAR(64) NOT NULL,
    last_used TIMESTAMP NOT NULL
);
